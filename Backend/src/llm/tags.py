# 표층형(부분 문자열) → 정규형. 동의어 묶음.
# (substring, canonical) 순서대로 평가 — 더 구체적인 것을 위에 둘 것.
SURFACE_TO_CANONICAL: tuple[tuple[str, str], ...] = (
    ("따뜻", "따뜻한"),
    ("뜨거", "따뜻한"),
    ("뜨끈", "따뜻한"),
    ("시원", "시원한"),
    ("차가", "시원한"),
    ("얼음", "시원한"),
    ("칼칼", "얼큰한"),
    ("얼큰", "얼큰한"),
    ("매콤", "얼큰한"),
    ("매운", "얼큰한"),
    ("맵", "얼큰한"),
    ("국물", "국물있는"),
    ("찌개", "국물있는"),
    ("탕", "국물있는"),
    ("담백", "담백한"),
    ("깔끔", "담백한"),
    ("진한", "진한"),
    ("깊은", "진한"),
    ("구수", "진한"),
    ("가벼", "가벼운"),
    ("가볍", "가벼운"),
    ("간단", "가벼운"),
    ("간편", "가벼운"),
    ("든든", "든든한"),
    ("배부르", "든든한"),
    ("푸짐", "든든한"),
    ("혼자", "혼밥"),
    ("혼밥", "혼밥"),
    ("해장", "해장"),
    ("야식", "야식"),
    ("바삭", "바삭한"),
    ("쫄깃", "쫄깃한"),
)


def normalize(tag: str) -> str:
    """LLM/사용자 표층 태그를 시드 정규형으로 매핑. 매칭 없으면 입력 그대로."""
    if not tag:
        return tag
    lowered = tag.strip().lower()
    for surface, canonical in SURFACE_TO_CANONICAL:
        if surface in lowered:
            return canonical
    return tag.strip()
