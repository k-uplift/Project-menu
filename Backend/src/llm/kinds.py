def classify_kind(menu_name: str) -> str | None:
    """메뉴명에서 음식 종류 substring 매칭 — Claude enrich의 폴백·검증용.

    가장 긴 매칭 우선 (예: "등심탕수육"이 "등심"·"탕수육"·"등심탕수육" 셋 다 매칭되면
    "등심탕수육"). 매칭 없으면 음료/주류 마커 확인. 그래도 없으면 None.

    Claude enrich가 메인. 이 함수는 키 없을 때 폴백 + 결과 검증용.
    """
    matches = [k for k in KINDS if k in menu_name]
    if matches:
        return max(matches, key=len)
    # 음료/주류 마커
    if any(m in menu_name for m in BEVERAGE_MARKERS):
        return KIND_OTHER_BEVERAGE
    if any(m in menu_name for m in ALCOHOL_MARKERS):
        return KIND_OTHER_ALCOHOL
    return None


